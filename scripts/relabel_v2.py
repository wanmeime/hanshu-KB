TYPE_CHARS = set('@=;#%&◆^~•!?{:[_$+※◈◉○◇')

def strip_marks(s):
    """保内容、剥符号、剥 |规范名 后缀与类型符号（v2 §6.1）"""
    def sub(m):
        inner = m.group(1).split('|', 1)[0]
        return inner[1:] if inner and inner[0] in TYPE_CHARS else inner
    s = re.sub(r'〖([^〗]*)〗', sub, s)
    s = re.sub(r'⟦([^⟧]*)⟧', sub, s)
    s = re.sub(r'〘([^〙]*)〙', sub, s)
    return s


def lint(s):
    problems = []
    if re.search(r'〖\s*〗|⟦\s*⟧|〘\s*〙', s):
        problems.append('空标注')
    if re.search(r'〖[^〗]*⟦|⟦[^⟧]*〖', s):
        problems.append('跨层嵌套疑似')
    if re.search(r'〖[^〗]*〖|⟦[^⟧]*⟦', s):
        problems.append('同层嵌套疑似')
    if '"' in s or "'" in s:
        problems.append('半角引号')
    for i, line in enumerate(s.split('\n'), 1):
        if line != line.rstrip():
            problems.append(f'第{i}行行尾空白')
    n1, n2 = s.count('〖'), s.count('〗')
    if n1 != n2:
        problems.append(f'〖〗不配对 {n1}/{n2}')
    n1, n2 = s.count('⟦'), s.count('⟧')
    if n1 != n2:
        problems.append(f'⟦⟧不配对 {n1}/{n2}')
    # 动词开括配名词闭括（乙1）
    if re.search(r'⟦[^⟧]*〗|〖[^〗]*⟧', s):
        problems.append('括号族混配')
    # 单字人名裸标扫描（v2 §6.2）
    singles = sorted(set(re.findall(r'〖@(.)〗', s)))
    if singles:
        problems.append('单字人名裸标: ' + ''.join(singles))
    return problems


def apply(juan):
    src = open(SRC[juan], encoding='utf-8').read()
    base = open(BASE[juan], encoding='utf-8').read()
    edits = E1 if juan == '001' else E2
    counts = collections.Counter()
    s = src
    for kind, old, new in edits:
        if kind == 're':
            n = s.count(old)
            if n == 0:
                print(f'  [警告] 未命中: {old!r}')
            s = s.replace(old, new)
            counts[old] += n
        elif kind == 'occur':
            parts = s.split(old)
            repls = new
            assert len(parts) - 1 == len(repls), f'{juan} occur {old}: {len(parts)-1} vs {len(repls)}'
            s = parts[0] + ''.join(r + parts[i+1] for i, r in enumerate(repls))
            counts[old] += len(repls)
        elif kind == 'scope':
            ch, mapping = old, new
            paras = re.split(r'(?m)^(?=\[1\.\d+\])', s)
            total = 0
            for i, p in enumerate(paras):
                m = re.match(r'\[([0-9.]+)\]', p)
                key = m.group(1) if m else None
                for canon, keys in mapping.items():
                    if key in keys:
                        n = p.count(f'〖@{ch}〗')
                        if n:
                            paras[i] = p.replace(f'〖@{ch}〗', f'〖@{ch}|{canon}〗')
                            total += n
            counts['〖@何〗(分段)'] += total
            s = ''.join(paras) if paras else s
            # re.split with lookahead keeps text; rejoin
    open(DST[juan], 'w', encoding='utf-8').write(s)

    # 完整性校验
    stripped = strip_marks(s)
    ok = stripped == base
    print(f'\n=== 卷{juan} ===')
    print(f'完整性: {"通过" if ok else "失败"}')
    if not ok:
        # 找出第一处差异
        for i, (a, b) in enumerate(zip(stripped, base)):
            if a != b:
                print(f'  首个差异@{i}: {stripped[max(0,i-15):i+15]!r} vs {base[max(0,i-15):i+15]!r}')
                break
        print(f'  长度: 标注剥离后 {len(stripped)} vs 底本 {len(base)}')
    probs = lint(s)
    print('lint:', probs if probs else '无问题')
    n_marks = len(re.findall(r'〖[^〗]*〗', s)) + len(re.findall(r'⟦[^⟧]*⟧', s)) + len(re.findall(r'〘[^〙]*〙', s))
    n_src = len(re.findall(r'〖[^〗]*〗', src)) + len(re.findall(r'⟦[^⟧]*⟧', src)) + len(re.findall(r'〘[^〙]*〙', src))
    print(f'标记数: {n_src} → {n_marks}')
    print('变更明细:')
    for k, v in counts.items():
        if v:
            print(f'  {k} ×{v}')
    total_changed = sum(counts.values())
    print(f'变更总数: {total_changed}')


if __name__ == '__main__':
    for j in ['001', '034']:
        apply(j)
